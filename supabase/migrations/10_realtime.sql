-- ============================================================
-- تفعيل Realtime على الجداول الحرجة
-- ============================================================
-- ملاحظة: Realtime يجب تفعيله فقط على الجداول التي تحتاجه فعلاً
-- لتجنب الحمل الزائد على السيرفر
-- ============================================================

-- 1. أوامر الشغل - للفنيين لمتابعة المهام المعينة لهم
ALTER PUBLICATION supabase_realtime ADD TABLE job_orders;

-- 2. بنود أمر الشغل - لمتابعة تحديثات البنود
ALTER PUBLICATION supabase_realtime ADD TABLE job_items;

-- 3. الفنيين المعينين - لإشعار الفنيين بتعيينات جديدة
ALTER PUBLICATION supabase_realtime ADD TABLE job_technicians;

-- 4. تقارير الدخول - للمشرفين لمتابعة الدخول الجديد
ALTER PUBLICATION supabase_realtime ADD TABLE assessments;

-- 5. حركات الخزينة - للمحاسبين لمتابعة الحركات اللحظية
ALTER PUBLICATION supabase_realtime ADD TABLE treasury_transactions;

-- 6. المدفوعات - لتحديث حالة الفواتير لحظياً
ALTER PUBLICATION supabase_realtime ADD TABLE payments;

-- ============================================================
-- ملخص الجداول المُفعّل عليها Realtime:
-- ============================================================
-- | الجدول               | السبب                                    |
-- |---------------------|------------------------------------------|
-- | job_orders          | إشعار الفنيين بأوامر جديدة/تحديثات       |
-- | job_items           | تتبع تقدم العمل لحظياً                   |
-- | job_technicians     | إشعار الفنيين عند تعيينهم                |
-- | assessments         | إشعار المشرفين بدخول سيارات جديدة        |
-- | treasury_transactions| مراقبة حركة الخزينة للمحاسبين            |
-- | payments            | تحديث حالة الفواتير عند الدفع            |
-- ============================================================

-- ============================================================
-- ⚠️ الجداول التي لم يتم تفعيل Realtime عليها (عمداً):
-- ============================================================
-- - customers, vehicles: لا تحتاج تحديثات لحظية
-- - products, inventory: التحديث عند الطلب كافي
-- - invoices: يتم تحديثها عبر payments
-- - activity_logs: للقراءة فقط، لا حاجة لـ realtime
-- - branches, profiles: بيانات ثابتة نسبياً
-- ============================================================
